import datetime
import hashlib
import os
import re
import struct
import sys

THIRD_PARTY = re.compile(r"^(mss|binkw|zlib|msvc|dbghelp|vampire_python)", re.I)
RTTI = re.compile(rb"\.\?A[VU][\x21-\x7e]+?@@(?=\0)")
IFACE = re.compile(rb"(?<![A-Za-z0-9_])[A-Z][A-Za-z]{3,}0\d\d(?![A-Za-z0-9@])")
ASSERT = re.compile(rb"[A-Za-z]:\\[\x20-\x7e]*?\.(?:cpp|c|h)\b", re.I)
MACHINES = {0x14C: "x86", 0x8664: "x64", 0x1C0: "arm", 0xAA64: "arm64"}


def cstr(d, o):
    e = d.index(b"\0", o)
    return d[o:e].decode("latin-1")


def parse(d):
    pe = struct.unpack_from("<I", d, 0x3C)[0]
    assert d[pe:pe + 4] == b"PE\0\0"
    machine, nsec, stamp, _, _, osz, _ = struct.unpack_from("<HHIIIHH", d, pe + 4)
    opt = pe + 24
    magic = struct.unpack_from("<H", d, opt)[0]
    lmaj, lmin = d[opt + 2], d[opt + 3]
    dd = opt + (96 if magic == 0x10B else 112)
    dirs = [struct.unpack_from("<II", d, dd + 8 * i) for i in range(min(16, struct.unpack_from("<I", d, dd - 4)[0]))]
    secs = []
    for i in range(nsec):
        n, vs, va, rs, rp = struct.unpack_from("<8sIIII", d, opt + osz + 40 * i)
        secs.append((n.rstrip(b"\0").decode("latin-1"), vs, va, rs, rp))

    def off(rva):
        for _, vs, va, rs, rp in secs:
            if va <= rva < va + max(vs, rs):
                return rva - va + rp
        raise ValueError(rva)

    ptr = 4 if magic == 0x10B else 8
    info = {"machine": machine, "stamp": stamp, "linker": f"{lmaj}.{lmin}",
            "sections": [(s[0], s[1]) for s in secs], "pdb": "", "imports": {}, "exports": []}

    def d_(i):
        return dirs[i] if i < len(dirs) else (0, 0)

    rva, size = d_(6)
    if rva:
        try:
            o = off(rva)
            for k in range(size // 28):
                t, sz, _, ptr_raw = struct.unpack_from("<IIII", d, o + 28 * k + 12)
                sig = d[ptr_raw:ptr_raw + 4]
                if t == 2 and sig in (b"RSDS", b"NB10"):
                    info["pdb"] = cstr(d, ptr_raw + (24 if sig == b"RSDS" else 16))
        except (ValueError, struct.error):
            pass

    rva, _ = d_(1)
    if rva:
        o = off(rva)
        while True:
            oft, _, _, name, ft = struct.unpack_from("<IIIII", d, o)
            if not name:
                break
            dll = cstr(d, off(name)).lower()
            t = off(oft or ft)
            fns = info["imports"].setdefault(dll, set())
            while True:
                v = int.from_bytes(d[t:t + ptr], "little")
                if not v:
                    break
                if v >> (ptr * 8 - 1):
                    fns.add(f"#{v & 0xFFFF}")
                else:
                    fns.add(cstr(d, off(v) + 2))
                t += ptr
            o += 20

    rva, _ = d_(0)
    if rva:
        o = off(rva)
        nnames, names = struct.unpack_from("<II", d, o + 24)[0], struct.unpack_from("<I", d, o + 32)[0]
        if nnames:
            n = off(names)
            info["exports"] = sorted(cstr(d, off(struct.unpack_from("<I", d, n + 4 * i)[0])) for i in range(nnames))
    return info


def inspect(path, rel):
    d = open(path, "rb").read()
    i = parse(d)
    i["path"] = rel
    i["size"] = len(d)
    i["sha"] = hashlib.sha256(d).hexdigest()
    i["date"] = datetime.datetime.fromtimestamp(i["stamp"], datetime.timezone.utc).strftime("%Y-%m-%d")
    i["rtti"] = sorted({m.decode() for m in RTTI.findall(d)})
    i["ifaces"] = sorted({m.decode() for m in IFACE.findall(d)})
    i["asserts"] = len({m.decode().lower() for m in ASSERT.findall(d)})
    i["third"] = bool(THIRD_PARTY.match(os.path.basename(rel)))
    return i


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="\n", encoding="utf-8") as f:
        f.write(text)


def main(game, out):
    bins = []
    for root, _, files in os.walk(game):
        for f in files:
            if f.lower().endswith((".exe", ".dll", ".asi")):
                p = os.path.join(root, f)
                bins.append(inspect(p, os.path.relpath(p, game).replace(os.sep, "/")))
    bins.sort(key=lambda b: b["path"].lower())

    L = ["# Binary inventory", "",
         "Generated by `tools/pe_inventory.py`. Vanilla Steam 1.2 copy; metadata only.", "",
         "| Binary | Size | SHA-256 | Machine | Built (UTC) | Linker | PDB | Imports | Named exports | CreateInterface | CDAPFN | RTTI | Interfaces | Assert paths | Sections |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for b in bins:
        L.append("| {} | {} | `{}` | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} |".format(
            b["path"], b["size"], b["sha"], MACHINES.get(b["machine"], hex(b["machine"])), b["date"], b["linker"],
            f"`{b['pdb']}`" if b["pdb"] else "-",
            ", ".join(f"{k}({len(v)})" for k, v in sorted(b["imports"].items())) or "-",
            len(b["exports"]),
            "yes" if "CreateInterface" in b["exports"] else "no",
            sum(e.startswith("CDAPFN") for e in b["exports"]), len(b["rtti"]),
            ", ".join(b["ifaces"]) or "-", b["asserts"],
            ", ".join(f"{n}:{s}" for n, s in b["sections"])))
    L += ["", "Exports sample (first 5 names, sorted):", ""]
    for b in bins:
        if b["exports"]:
            L.append(f"- {b['path']}: " + ", ".join(b["exports"][:5]))

    L += ["", "## Windows API surface", "",
          "Unique imported functions per DLL, counted across the binaries of each group.", ""]
    shipped = {os.path.basename(b["path"]).lower() for b in bins}
    for kind, flag in (("game binaries", False), ("third-party binaries", True)):
        for title, ship in (("Windows system DLLs", False), ("Shipped DLLs", True)):
            agg = {}
            for b in bins:
                if b["third"] == flag:
                    for dll, fns in b["imports"].items():
                        if (dll in shipped) == ship:
                            agg.setdefault(dll, set()).update(fns)
            L += [f"### {title} imported by {kind}", "", "| DLL | Unique functions |", "|---|---|"]
            L += [f"| {k} | {len(v)} |" for k, v in sorted(agg.items())]
            L.append("")
    write(os.path.join(out, "inventory.md"), "\n".join(L))

    for b in bins:
        name = os.path.basename(b["path"]).lower()
        if not b["third"]:
            write(os.path.join(out, "inventory", f"rtti-{name}.txt"), "".join(r + "\n" for r in b["rtti"]))
        write(os.path.join(out, "inventory", f"imports-{name}.txt"),
              "".join(f"{dll}!{fn}\n" for dll, fns in sorted(b["imports"].items()) for fn in sorted(fns)))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
