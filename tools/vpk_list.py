import collections
import glob
import os
import re
import struct
import sys
from typing import NamedTuple

TOKENS = {(hi << 16) | (ma << 8) | mi for hi in (0xFFFE, 0xFFFF) for ma, mi in ((1, 0), (1, 1), (1, 2), (1, 3), (1, 4), (2, 0), (3, 0))}


class Entry(NamedTuple):
    path: str
    size: int
    archive: str
    offset: int
    limit: int
    dir_only: bool


def pack_paths(game):
    return sorted(glob.glob(os.path.join(game, "Vampire", "pack[0-9][0-9][0-9].vpk")))


def read_pack(path):
    size = os.path.getsize(path)
    if size < 9:
        raise ValueError("%s: shorter than the 9-byte trailer" % path)
    with open(path, "rb") as f:
        f.seek(size - 9)
        count, dir_off, ver = struct.unpack("<IIB", f.read(9))
        if ver not in (0, 1):
            raise ValueError("%s: unknown version %d" % (path, ver))
        if dir_off > size - 9:
            raise ValueError(path)
        f.seek(dir_off)
        buf = f.read(size - 9 - dir_off)
    name = os.path.basename(path)
    out = []
    p = 0
    for _ in range(count):
        if p + 4 > len(buf):
            raise ValueError(path)
        (n,) = struct.unpack_from("<I", buf, p)
        if p + 12 + n > len(buf):
            raise ValueError(path)
        title = buf[p + 4 : p + 4 + n].decode("latin-1")
        off, sz = struct.unpack_from("<II", buf, p + 4 + n)
        if off + sz > dir_off:
            raise ValueError(path)
        out.append(Entry(title, sz, name, off, dir_off, ver == 1))
        p += 12 + n
    if p != len(buf):
        raise ValueError(path)
    return out


def all_entries(game):
    return [e for p in pack_paths(game) for e in read_pack(p)]


def read_entry(game, e):
    with open(os.path.join(game, "Vampire", e.archive), "rb") as f:
        f.seek(e.offset)
        return f.read(e.size)


def model(token):
    return "%s_%d_%d" % ("vs" if token >> 16 == 0xFFFE else "ps", (token >> 8) & 255, token & 255)


def vcs_tokens(b):
    if len(b) < 20:
        return [-1]
    (n,) = struct.unpack_from("<I", b, 4)
    fit = min(n, (len(b) - 20) // 8)
    out = []
    for i in range(fit):
        off, sz = struct.unpack_from("<II", b, 20 + 8 * i)
        if sz == 0:
            out.append(0)
            continue
        t = struct.unpack_from("<I", b, off)[0] if sz >= 4 and off + sz <= len(b) else -1
        out.append(t if t in TOKENS else -1)
    return out + [-1] * (fit < n)


def psh_model(b):
    m = re.match(rb"\s*(ps|vs)\.(\d)\.(\d)", b, re.I)
    return "%s_%s_%s" % (m[1].decode().lower(), m[2].decode(), m[3].decode()) if m else None


def vmt_shader(b):
    t = re.sub(rb"//[^\n]*", b"", b)
    m = re.search(rb'"?([A-Za-z0-9_]+)"?', t)
    return m[1].decode().lower() if m else None


def table(head, rows):
    return ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]


def ext(p):
    return os.path.splitext(p)[1].lower() or "(none)"


def inventory(game):
    es = all_entries(game)
    files = [e for e in es if not e.dir_only]
    dirs = [e for e in es if e.dir_only]
    L = ["# VPK inventory", ""]
    L += ["Generated by `python3 -I tools/vpk_list.py inventory <game dir>` from the vanilla Steam 1.2 copy. Paths, sizes and counts only.", ""]
    L += ["Format facts: the layout is derived from the files and cross-checked against the MIT-licensed sourcepp `vpkpp` VTMB reader (https://github.com/craftablescience/sourcepp, `src/vpkpp/format/VPK_VTMB.cpp`). Each `packNNN.vpk` ends with a 9-byte trailer (u32 file count, u32 directory offset, u8 version); the directory at that offset is `count` records of u32 name length, name, u32 offset, u32 size, little-endian, and payload bytes are stored raw (no compression) at `offset` in the same archive. Version 1 (only `pack010.vpk`) is skipped by sourcepp (it accepts version 0 only); reading its records as directory names (offset 0, size 0) is our own inference from the file, not a documented fact.", ""]
    L += ["## Totals", ""]
    L += ["- archives: %d" % len(pack_paths(game)), "- file entries: %d (%d bytes)" % (len(files), sum(e.size for e in files)), "- directory records: %d" % len(dirs)]
    names = collections.Counter(e.path.lower() for e in files)
    dup = sorted(n for n, c in names.items() if c > 1)
    L += ["- paths present in more than one archive: %d" % len(dup), ""]
    L += ["Duplicated paths (case-insensitive):", ""] + ["- `%s`: %s" % (n, ", ".join(sorted(e.archive for e in files if e.path.lower() == n))) for n in dup] + ["", "pack103.vpk contains only these 7 paths; which copy the engine prefers is not established here.", ""]
    L += ["## Per archive", ""]
    arch = [os.path.basename(p) for p in pack_paths(game)]
    L += table(["archive", "file size", "files", "payload bytes", "directory records"], [(a, os.path.getsize(os.path.join(game, "Vampire", a)), sum(1 for e in files if e.archive == a), sum(e.size for e in files if e.archive == a), sum(1 for e in dirs if e.archive == a)) for a in arch])
    L += ["", "## Per extension (file entries)", ""]
    c = collections.Counter(ext(e.path) for e in files)
    s = collections.Counter()
    for e in files:
        s[ext(e.path)] += e.size
    L += table(["extension", "files", "bytes"], [(k, c[k], s[k]) for k in sorted(c)])
    L += ["", "## Per top-level directory (file entries)", ""]
    top = collections.Counter(e.path.split("/")[0] if "/" in e.path else "(root)" for e in files)
    L += table(["directory", "files"], sorted(top.items()))
    n = lambda *x: sum(c[k] for k in x)
    loose = []
    for root, ds, fs in os.walk(os.path.join(game, "Vampire")):
        ds.sort()
        for f in sorted(fs):
            if not re.fullmatch(r"pack\d{3}\.vpk", f) or root != os.path.join(game, "Vampire"):
                full = os.path.join(root, f)
                loose.append((os.path.relpath(full, os.path.join(game, "Vampire")), os.path.getsize(full)))
    lc = collections.Counter(ext(p) for p, _ in loose)
    L += ["", "## Asset counts", ""]
    L += table(["kind", "in packs", "loose in Vampire/"], [
        ("maps (.bsp)", n(".bsp"), lc[".bsp"]),
        ("materials (.vmt)", n(".vmt"), lc[".vmt"]),
        ("textures (.tth, .ttz, .tga)", n(".tth", ".ttz", ".tga"), lc[".tth"] + lc[".ttz"] + lc[".tga"]),
        ("models (.mdl)", n(".mdl"), lc[".mdl"]),
        ("model mesh data (.vtx, .phy)", n(".vtx", ".phy"), lc[".vtx"] + lc[".phy"]),
        ("sounds (.wav)", n(".wav"), lc[".wav"]),
    ])
    L += ["", "## Python", ""]
    py = sorted((e for e in files if ext(e.path) in (".py", ".pyc")), key=lambda e: e.path)
    L += ["In packs: %d `.py`/`.pyc` entries." % len(py), ""]
    L += table(["path", "archive", "size"], [(e.path, e.archive, e.size) for e in py])
    lp = [(p, sz) for p, sz in loose if ext(p) in (".py", ".pyc")]
    L += ["", "Loose under Vampire/: %d `.py`/`.pyc` files, %d bytes." % (len(lp), sum(sz for _, sz in lp)), ""]
    L += ["## Loose files outside the packs (Vampire/)", ""]
    ls = collections.Counter()
    for p, sz in loose:
        ls[ext(p)] += sz
    L += table(["extension", "files", "bytes"], [(k, lc[k], ls[k]) for k in sorted(lc)])
    L += ["", "## Shaders", ""]
    L += ["Shader bytecode is in the packs, not in the DLLs. Compiled shaders are `.vcs` files under `shaders/vsh/`, `shaders/psh/` (vs/ps 1.x assembly) and `shaders/fxc/` (HLSL, compiled). As derived from the files (no published spec was used), each `.vcs` is a header of five u32 (second word = number of combos) followed by one (offset, size) pair per combo, each pointing at a raw D3D9 token stream whose first dword is the version token. `materials/dxshaders/*.psh` are plain-text pixel shader assembly sources whose first line names the model.", ""]
    L += ["Version token encoding, per Microsoft's driver documentation page `Version Token` (https://learn.microsoft.com/en-us/windows-hardware/drivers/display/version-token): bits 31:16 are 0xFFFE for a vertex shader and 0xFFFF for a pixel shader, bits 15:8 the major and bits 7:0 the minor version. See also the macro pages: https://learn.microsoft.com/en-us/windows/win32/direct3d9/d3dvs-version , https://learn.microsoft.com/en-us/windows/win32/direct3d9/d3dps-version , https://learn.microsoft.com/en-us/windows/win32/direct3d9/d3dxgetshaderversion .", ""]
    vcs = sorted((e for e in files if e.path.startswith("shaders/") and ext(e.path) == ".vcs"), key=lambda e: (e.path, e.archive))
    psh = sorted((e for e in files if e.path.startswith("materials/dxshaders/") and ext(e.path) == ".psh"), key=lambda e: (e.path, e.archive))
    rows = []
    combos = collections.Counter()
    nfiles = collections.Counter()
    bad = empty = 0
    for e in vcs:
        ts = vcs_tokens(read_entry(game, e))
        bad += ts.count(-1)
        empty += ts.count(0)
        ms = collections.Counter(("0x%08X" % t, model(t)) for t in ts if t > 0)
        for k, v in ms.items():
            combos[(e.path.split("/")[1], k)] += v
            nfiles[(e.path.split("/")[1], k)] += 1
        rows.append((e.path, e.archive, e.size, ", ".join("%s x%d" % (k[1], v) for k, v in sorted(ms.items(), key=lambda kv: kv[0][1]))))
    L += ["### Compiled `.vcs` per directory and model", ""]
    L += table(["directory", "token", "model", "files", "compiled shaders"], [(d, t, m, nfiles[(d, (t, m))], combos[(d, (t, m))]) for d, (t, m) in sorted(combos)])
    L += ["", "### Compiled `.vcs` per model, all directories", ""]
    tot = collections.Counter()
    tf = collections.Counter()
    for (d, k), v in combos.items():
        tot[k] += v
        tf[k] += nfiles[(d, k)]
    L += table(["token", "model", "files", "compiled shaders"], [(t, m, tf[(t, m)], tot[(t, m)]) for t, m in sorted(tot, key=lambda k: (k[1][:2], k[1]))])
    L += ["", "%d `.vcs` files, %d compiled shaders, %d empty combos, %d combos without a valid version token." % (len(vcs), sum(tot.values()), empty, bad), ""]
    pm = collections.Counter()
    prow = []
    for e in psh:
        m = psh_model(read_entry(game, e))
        pm[m or "(unparsed)"] += 1
        prow.append((e.path, e.archive, e.size, m or "(unparsed)"))
    L += ["### Text `.psh` sources per model (from the first line)", ""]
    L += table(["model", "files"], sorted(pm.items()))
    L += ["", "### Shader names used by `.vmt` materials (first keyword of each file)", ""]
    vn = collections.Counter(vmt_shader(read_entry(game, e)) or "(unparsed)" for e in files if ext(e.path) == ".vmt")
    L += table(["shader", "materials"], sorted(vn.items()))
    L += ["", "### Shader-related entries outside `.vcs`/`.psh`", ""]
    other = collections.Counter(ext(e.path) for e in files if e.path.startswith("materials/shadertest/"))
    L += ["`materials/shadertest/` holds test materials and textures: " + ", ".join("%d %s" % (other[k], k) for k in sorted(other)) + ".", ""]
    L += ["### DLLs", ""]
    L += ["Version tokens for vs/ps 1.0 to 3.0 found as raw dwords in the loaded shader DLLs (none means no embedded bytecode). The three hits in `shaderapidx9.dll` are x86 immediates (`mov dword [esp], 0xFFFF0101` and a `cmp` against 0xFFFF0200 at file offsets 0x2D1AD, 0x2D547, 0x2D9DA), so the runtime builds or checks tiny token streams in code, and loads the real shaders from the packs:", ""]
    dl = []
    for p in sorted(glob.glob(os.path.join(game, "Bin", "stdshader_*.dll")) + [os.path.join(game, "Bin", "shaderapidx9.dll")]):
        with open(p, "rb") as f:
            d = f.read()
        dl.append((os.path.basename(p), sum(d.count(struct.pack("<I", t)) for t in TOKENS), "yes" if b"shaders\\fxc\\" in d else "no"))
    L += table(["dll", "version tokens", "mentions `shaders\\fxc\\`"], dl)
    L += ["", "### Every `.vcs` entry", ""]
    L += table(["path", "archive", "size", "models"], rows)
    L += ["", "### Every `.psh` entry", ""]
    L += table(["path", "archive", "size", "model"], prow)
    return "\n".join(L) + "\n"


def main(argv):
    usage = "usage: vpk_list.py list <game> | extract <game> <entry> <out> [archive] | inventory <game>"
    need = {"list": 3, "inventory": 3, "extract": 5}
    if len(argv) < 2 or argv[1] not in need or len(argv) < need[argv[1]] or len(argv) > need[argv[1]] + (argv[1] == "extract"):
        print(usage, file=sys.stderr)
        raise SystemExit(2)
    cmd, game = argv[1], argv[2]
    if cmd == "list":
        for e in all_entries(game):
            print("%s\t%d\t%s\t%d" % (e.path, e.size, e.archive, e.offset))
    elif cmd == "extract":
        hits = [e for e in all_entries(game) if e.path == argv[3] and not e.dir_only and (len(argv) < 6 or e.archive == argv[5])]
        if not hits:
            raise SystemExit("no entry: %s" % argv[3])
        if len(hits) > 1:
            raise SystemExit("%s is in several archives (%s): pass one as the last argument" % (argv[3], ", ".join(h.archive for h in hits)))
        e = hits[0]
        with open(argv[4], "wb") as f:
            f.write(read_entry(game, e))
    elif cmd == "inventory":
        sys.stdout.write(inventory(game))


if __name__ == "__main__":
    main(sys.argv)
